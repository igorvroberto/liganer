LEADS.extend(LEADS_SETORES)

def main():
    out = Path(__file__).parent / "LEADS.csv"
    rows = []
    for i, lead in enumerate(LEADS, start=1):
        row = {"id": f"ARA-{i:03d}", **lead}
        det = remap_categoria_detalhada(lead)
        row["linha"] = infer_linha({**lead, "categoria": det})
        row["categoria"] = encurtar_categoria(det)
        # Subcategorias legadas (CD2, M1…) não se aplicam ao novo vocabulário
        row["subcategoria"] = ""
        if not (row.get("crm") or "").strip():
            row["crm"] = "Sem cadastro"
        rows.append(row)
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=HEADERS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    print(f"Wrote {len(rows)} leads → {out}")

    # Contagens
    from collections import Counter
    cat = Counter(r["categoria"] for r in rows)
    pot = Counter(r["potencial"] for r in rows)
    lin = Counter(r["linha"] for r in rows)
    print("Por categoria:", dict(cat))
    print("Por potencial:", dict(pot))
    print("Por linha:", dict(lin))

if __name__ == "__main__":
    main()
